#!/usr/bin/env python3
"""Stage 9 report: summarise scripts/extract.py outputs.

Reads extracted-*.jsonl.gz and writes a markdown report: coverage of each
field, page types, top states, parks and features, and a random sample of
located pages for eyeballing. Stdlib only.

Usage:
  scripts/extract_report.py --in 'extracted-*.jsonl.gz' --out report.md
"""
import argparse
import glob
import gzip
import json
import random
from collections import Counter


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in", dest="inputs", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    n = 0
    have = Counter()
    types, states, parks, feats, sites = Counter(), Counter(), Counter(), Counter(), Counter()
    located = []
    for path in sorted({p for pat in args.inputs for p in glob.glob(pat)}):
        with gzip.open(path, "rt") as f:
            for line in f:
                r = json.loads(line)
                n += 1
                types[r["page_type"]] += 1
                for k in ("distance_mi", "gain_ft", "date"):
                    have[k] += r[k] is not None
                have["3+ features"] += len(r["features"]) >= 3
                if r["location"]:
                    have["location"] += 1
                    L = r["location"]
                    states[L["state"]] += 1
                    if L["park"]:
                        parks[L["park"]] += 1
                    sites[r["site"]] += 1
                    located.append(r)
                for ft in r["features"]:
                    feats[(ft["name"], ft["state"], ft["kind"])] += 1

    pct = lambda v: f"{100 * v / n:.0f}%" if n else "–"
    L = []
    w = L.append
    w("# Stage 9 report: first extraction pass\n")
    w(f"Generated by `scripts/extract_report.py` over {n:,} kept pages.\n")
    w("| field | pages | share |\n|---|---:|---:|")
    for k in ("location", "3+ features", "distance_mi", "gain_ft", "date"):
        w(f"| {k} | {have[k]:,} | {pct(have[k])} |")
    w("\n## Page types\n")
    w("| type | pages | share |\n|---|---:|---:|")
    for k, v in types.most_common():
        w(f"| {k} | {v:,} | {pct(v)} |")
    for title, c, k in (("States (located pages)", states, 25), ("Parks", parks, 30), ("Sites (located pages)", sites, 25)):
        w(f"\n## {title}\n")
        w("| | pages |\n|---|---:|")
        for name, v in c.most_common(k):
            w(f"| {name} | {v:,} |")
    w("\n## Most-mentioned features (pages)\n")
    w("| feature | state | kind | pages |\n|---|---|---|---:|")
    for (name, st, kind), v in feats.most_common(40):
        w(f"| {name} | {st} | {kind} | {v:,} |")
    w("\n## Random located pages\n")
    w("| page | type | state / park | distance | gain | features |\n|---|---|---|---:|---:|---|")
    for r in random.Random(8).sample(located, min(40, len(located))):
        t = (r["title"] or r["url"])[:70].replace("|", "/")
        loc = r["location"]
        fs = "; ".join(f["name"] for f in r["features"][:4]).replace("|", "/")
        w(f"| [{t}]({r['url']}) | {r['page_type']} | {loc['state']} / {loc['park'] or ''} | "
          f"{r['distance_mi'] or ''} | {r['gain_ft'] or ''} | {fs} |")
    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{n:,} pages, {have['location']:,} located")


if __name__ == "__main__":
    main()
