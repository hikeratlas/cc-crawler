#!/usr/bin/env python3
"""First-cut Stage 3 scoring plus an evaluation report (stdlib only).

Reads the output of cmd/hubscore and writes:
  - a scored, ranked seed list (gzip TSV), and
  - a Markdown report: hub in-degrees, recall on data/eval/known_blogs.csv
    (dev and holdout), where the negatives land, and the top-ranked domains.

Score (see docs/DESIGN.md, Stage 3):
  idf(h)       = ln(N / in_degree(h))           N = number of domains in the graph
  specificity  = 1 / (1 + ln(1 + out_degree / 100))
  score        = specificity * sum over linked hubs of weight(h) * idf(h)

Usage:
  scripts/seed_report.py SCORES.tsv.gz HUB_STATS.tsv --meta meta.json \
      --seeds-out seeds.tsv.gz --report-out report.md
"""
import argparse
import csv
import gzip
import json
import math
import random
from collections import Counter


def read_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scores")
    ap.add_argument("hub_stats")
    ap.add_argument("--meta", help="meta.json from cmd/hubscore (supplies release and vertex count)")
    ap.add_argument("--release")
    ap.add_argument("--vertices", type=int, help="number of domains in the graph")
    ap.add_argument("--known", default="data/eval/known_blogs.csv")
    ap.add_argument("--negatives", default="data/eval/negatives.csv")
    ap.add_argument("--seeds-out", required=True)
    ap.add_argument("--report-out", required=True)
    ap.add_argument("--min-hubs", type=int, default=2, help="seed threshold on distinct hubs")
    args = ap.parse_args()
    if args.meta:
        with open(args.meta) as f:
            meta = json.load(f)
        args.release = args.release or meta["release"]
        args.vertices = args.vertices or meta["vertices"]
    if not args.release or not args.vertices:
        ap.error("need --meta, or both --release and --vertices")

    hubs = {}
    with open(args.hub_stats) as f:
        for r in csv.DictReader(f, delimiter="\t"):
            indeg = int(r["in_degree"])
            r["idf"] = math.log(args.vertices / indeg) if indeg > 0 else 0.0
            hubs[r["hub"]] = r

    rows = []
    with gzip.open(args.scores, "rt") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            linked = [h for h in r["hubs"].split(",") if h]
            out_deg = int(r["out_degree"])
            spec = 1.0 / (1.0 + math.log(1.0 + out_deg / 100.0))
            raw = sum(float(hubs[h]["weight"]) * hubs[h]["idf"] for h in linked)
            r["n_hubs"] = int(r["n_hubs"])
            r["n_cats"] = len([c for c in r["categories"].split(",") if c])
            r["score"] = raw * spec
            rows.append(r)
    rows.sort(key=lambda r: -r["score"])
    for i, r in enumerate(rows, 1):
        r["rank"] = i
    by_domain = {r["domain"]: r for r in rows}

    with gzip.open(args.seeds_out, "wt") as f:
        cols = ["rank", "domain", "score", "n_hubs", "n_cats", "out_degree", "n_hosts", "categories", "hubs"]
        f.write("\t".join(cols) + "\n")
        for r in rows:
            if r["n_hubs"] >= 1:
                f.write("\t".join(f"{r[c]:.3f}" if c == "score" else str(r[c]) for c in cols) + "\n")

    linked = [r for r in rows if r["n_hubs"] >= 1]
    seeds = [r for r in linked if r["n_hubs"] >= args.min_hubs]
    known = read_csv(args.known)
    negs = read_csv(args.negatives)
    L = []
    w = L.append

    w(f"# Stage 2–3 report: {args.release}\n")
    w("Generated by `scripts/seed_report.py` from `cmd/hubscore` output. Scores are a first cut; see DESIGN.md Stage 3.\n")
    w("## Funnel\n")
    w("| | domains |\n|---|---:|")
    w(f"| in graph | {args.vertices:,} |")
    w(f"| link to ≥ 1 hub | {len(linked):,} |")
    for k in (2, 3, 5, 8):
        w(f"| link to ≥ {k} hubs | {sum(1 for r in linked if r['n_hubs'] >= k):,} |")
    w(f"| ≥ {args.min_hubs} hubs in ≥ 2 categories | {sum(1 for r in seeds if r['n_cats'] >= 2):,} |")
    w("")

    w("## Hubs by in-degree\n")
    w("How many domains link to each hub. Low in-degree hubs are the most specific signal (high idf).\n")
    w("| hub | category | weight | linking domains | idf |\n|---|---|---:|---:|---:|")
    for h in sorted(hubs.values(), key=lambda h: -int(h["in_degree"])):
        w(f"| {h['hub']} | {h['category']} | {float(h['weight']):.1f} | {int(h['in_degree']):,} | {h['idf']:.2f} |")
    w("")

    def eval_table(items, title, note):
        w(f"## {title}\n")
        w(note + "\n")
        w("| domain | split | hubs | categories | out-degree | score | rank |\n|---|---|---:|---|---:|---:|---:|")
        for it in sorted(items, key=lambda it: by_domain.get(it["domain"], {}).get("rank", 10**12)):
            r = by_domain.get(it["domain"])
            split = it.get("split", it.get("reason", ""))
            if not r:
                w(f"| {it['domain']} | {split} | – | not in graph | – | – | – |")
            elif int(r["out_degree"]) == 0:
                w(f"| {it['domain']} | {split} | – | no outlinks: not crawled in this window | 0 | – | – |")
            else:
                w(f"| {it['domain']} | {split} | {r['n_hubs']} | {r['categories'] or '–'} | {int(r['out_degree']):,} | {r['score']:.1f} | {r['rank']:,} |")
        w("")

    w("## Recall on known blogs\n")
    w(f"Share of known blogs that pass each threshold. The seed threshold is ≥ {args.min_hubs} distinct hubs.\n")
    w("| threshold | dev | holdout | all |\n|---|---:|---:|---:|")
    for k in (1, 2, 3, 5):
        cells = []
        for split in ("dev", "holdout", None):
            group = [it for it in known if split is None or it["split"] == split]
            hit = sum(1 for it in group if by_domain.get(it["domain"], {}).get("n_hubs", 0) >= k)
            cells.append(f"{hit}/{len(group)} ({100 * hit / max(1, len(group)):.0f}%)")
        w(f"| ≥ {k} hubs | " + " | ".join(cells) + " |")
    w("")
    eval_table(known, "Known blogs", "Lower rank is better. A blog with 0–1 hubs is invisible to this stage. \"No outlinks\" means the domain is in the graph only as a link target: Common Crawl did not fetch it in this graph's crawls (robots.txt or edge blocking of CCBot, or simply not reached).")
    eval_table(negs, "Negatives", "These should rank low or fail the threshold. Ones that score high tell us what Stage 3 must filter.")

    w("## Top 75 by score\n")
    w("| rank | domain | hubs | categories | out-degree | score |\n|---:|---|---:|---|---:|---:|")
    for r in rows[:75]:
        w(f"| {r['rank']} | {r['domain']} | {r['n_hubs']} | {r['categories']} | {int(r['out_degree']):,} | {r['score']:.1f} |")
    w("")

    rnd = random.Random(42)
    mid = [r for r in seeds if r["n_cats"] >= 2]
    sample = rnd.sample(mid, min(60, len(mid)))
    sample.sort(key=lambda r: r["rank"])
    w(f"## Random sample of 60 seeds (≥ {args.min_hubs} hubs, ≥ 2 categories)\n")
    w("For eyeballing precision across the whole seed set, not just the top.\n")
    w("| rank | domain | hubs | out-degree | score |\n|---:|---|---:|---:|---:|")
    for r in sample:
        w(f"| {r['rank']:,} | {r['domain']} | {r['n_hubs']} | {int(r['out_degree']):,} | {r['score']:.1f} |")
    w("")

    tld = Counter(r["domain"].rsplit(".", 1)[-1] for r in seeds)
    w(f"## TLDs among seeds (≥ {args.min_hubs} hubs)\n")
    w("| tld | domains |\n|---|---:|")
    for t, n in tld.most_common(20):
        w(f"| .{t} | {n:,} |")
    w("")

    with open(args.report_out, "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    main()
